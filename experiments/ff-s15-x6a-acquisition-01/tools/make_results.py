"""Generates RESULTS.md from the receipts and guards every prose claim that names a finding.

  python tools/make_results.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = json.loads((ROOT / "results" / "x6a-receipt.json").read_text(encoding="ascii"))
X = json.loads((ROOT / "results" / "x6a-explore.json").read_text(encoding="ascii"))
L = R["levels"]
P3, P15, P5 = L["0.3"], L["0.15"], L["0.5"]
f3 = lambda v: f"{v:.3f}"  # noqa: E731
pp = lambda v: f"{100 * v:.1f}"  # noqa: E731

# ---- guards: the prose below names these findings
d = R["decision"]
assert d["outcome"] == "CONTINUE" and d["budgets_D_better_of_1_2_3"] == 3 and d["auc_ci_excludes_zero"], "the preregistered decision changed"
assert all(L[h]["decision"]["continue"] for h in L), "continuation no longer holds at every hiding level"
assert all(L[h]["oracle_unrecoverable"] == 0 for h in L)
for h, b in L.items():
    a = b["attribution"]
    assert a["D_no1"]["auc_minus_best_baseline"] > a["D_full"]["auc_minus_best_baseline"], "signal 1 no longer hurts"
    assert a["D_only3"]["auc_minus_best_baseline"] == a["D_no1"]["auc_minus_best_baseline"], "signal 2 now fires"
    assert a["D_only1"]["auc_minus_best_baseline"] == a["D_no3"]["auc_minus_best_baseline"]
    assert b["auc_0_to_6"]["C_broad"] - b["auc_0_to_6"]["A_random"] < 0.02, "broad producer acquisition now differs from random"
    assert b["auc_0_to_6"]["B_confidence"] > 3 * b["auc_0_to_6"]["A_random"]
assert P3["attribution"]["D_no3"]["share_of_gain_lost"] > 1.0, "signal 3 no longer carries the whole gain"
assert set(P3["D_signal_firings_first40_per_world"]) == {"missing_slot", "repair"}, "signal 2 (conflict) or the fallback now fires"
XL = X["levels"]
for h, b in XL.items():
    assert b["auc_diff"]["S_schema_conf-B_confidence"]["ci95"][0] > 0.1, "the schema-only control no longer beats B clearly"
    assert b["auc_diff"]["D_full-S_schema_conf"]["ci95"][1] < 0, "D_full no longer loses to the schema-only control"
    assert b["harm_diff"]["D_only3-S_schema_conf"]["ci95"][0] > 0, "signal 3 no longer raises wrong-ACT rate over the schema rule"
assert XL["0.15"]["auc_diff"]["D_only3-S_schema_conf"]["ci95"][0] < 0 < XL["0.15"]["auc_diff"]["D_only3-S_schema_conf"]["ci95"][1], "graph increment now significant at h=0.15"
assert XL["0.3"]["auc_diff"]["D_only3-S_schema_conf"]["ci95"][0] > 0 and XL["0.5"]["auc_diff"]["D_only3-S_schema_conf"]["ci95"][0] > 0

# ---- tables
names = ["A_random", "B_confidence", "C_broad", "D_full", "D_no1", "D_no3", "D_only3", "O_oracle"]
freq = ["| policy | " + " | ".join(f"b={b}" for b in range(0, 9)) + " | AUC 0-6 |", "|---|" + "---|" * 10]
for n in names:
    freq.append(f"| {n} | " + " | ".join(f3(v) for v in P3["recovery_by_budget"][n]) + f" | {f3(P3['auc_0_to_6'][n])} |")
lv = ["| h | needs recovery | already correct | silent wrong ACT | AUC B | AUC D_full | AUC D_only3 | AUC oracle | D_full - best baseline AUC (95%) |", "|---|---|---|---|---|---|---|---|---|"]
for h, b in L.items():
    c = b["classes"]
    g = b["auc_gain"]
    lv.append(f"| {h} | {c['needs_recovery']} | {c['already_correct']} | {c['silent_wrong']} | {f3(b['auc_0_to_6']['B_confidence'])} | {f3(b['auc_0_to_6']['D_full'])} | {f3(b['auc_0_to_6']['D_only3'])} | {f3(b['auc_0_to_6']['O_oracle'])} | {f3(g['median'])} ({f3(g['ci95'][0])} to {f3(g['ci95'][1])}) |")
ex = ["| h | schema-only control minus B | D_full minus schema-only | D_only3 (signal 3) minus schema-only | wrong-ACT rate: B / schema-only / D_full / D_only3 |", "|---|---|---|---|---|"]
for h, b in XL.items():
    t = lambda k: f"{f3(b['auc_diff'][k]['median'])} ({f3(b['auc_diff'][k]['ci95'][0])} to {f3(b['auc_diff'][k]['ci95'][1])})"  # noqa: E731
    hm = b["harm"]
    ex.append(f"| {h} | {t('S_schema_conf-B_confidence')} | {t('D_full-S_schema_conf')} | {t('D_only3-S_schema_conf')} | {pp(hm['B_confidence'])}% / {pp(hm['S_schema_conf'])}% / {pp(hm['D_full'])}% / {pp(hm['D_only3'])}% |")
pol = ["| policy | queries per recovered world | empty queries per world | queries outside the oracle set per world | wrong-ACT rate |", "|---|---|---|---|---|"]
for n in names:
    v = P3["per_policy"][n]
    pol.append(f"| {n} | {v['queries_per_recovered']:.2f} | {v['empty_queries_per_world']:.2f} | {v['unnecessary_queries_per_world']:.2f} | {pp(v['harm_rate'])}% |")
atr = P3["attribution"]
xs = XL["0.3"]

md = f"""# X6-A results: deficiency-guided acquisition

**Status: exploratory. Preregistered rule: CONTINUE. Attribution: the gain is schema closure, not graph inference.** Generated by `tools/make_results.py` from `results/x6a-receipt.json` (preregistered analysis) and `results/x6a-explore.json` (post hoc, labelled). BANK-v1 DEV fold B only; the frozen X0 graph and controller (hash-checked against `13d87e83`); no BANK-v2, not C-G1b.

## Setup in one paragraph

{P3['worlds']} fold-B worlds whose oracle decision is a correct ACT. Each fact-bearing slot (object/agent location, switch state, per-location gate, per-location links) is hidden with probability `h`; `QUERY(slot)` reveals it at cost 1, empty queries included; the frozen controller is retried after every query and the episode stops at its first ACT (correct = recovered, wrong = harm). At `h = 0.3`: {P3['classes']['needs_recovery']} worlds need recovery, {P3['classes']['already_correct']} are already correct, {P3['classes']['silent_wrong']} are silent wrong ACTs that no acquisition can fix, and the oracle selector recovers all of the needs-recovery worlds.

## Preregistered verdict

D (graph deficiency: repair set, then conflict, then missing slot, falling back to confidence) beats the best of random, confidence and broad-producer acquisition at budgets 1, 2 and 3 with paired intervals excluding zero, and on the AUC, at `h = 0.15`, `0.3` and `0.5`. By the rule fixed in `PLAN.md` this is **CONTINUE**. At `h = 0.3` the AUC gain over the best baseline (confidence) is {f3(P3['auc_gain']['median'])} ({f3(P3['auc_gain']['ci95'][0])} to {f3(P3['auc_gain']['ci95'][1])}) against an oracle headroom of {f3(P3['auc_0_to_6']['O_oracle'] - P3['auc_0_to_6']['B_confidence'])}.

### Recovery by query budget at h = 0.3

{chr(10).join(freq)}

### Across hiding levels

{chr(10).join(lv)}

### Cost and waste at h = 0.3

{chr(10).join(pol)}

Random and broad-producer acquisition are indistinguishable: paying one query per slot of a family buys almost nothing, because most slots are empty by construction.

## Attribution (the preregistered ablations)

- The controller's conflict signal (signal 2) **never fired**: hiding facts cannot create a conflict. It is not exercised by this environment.
- Removing the missing-slot signal (signal 3) loses {100 * atr['D_no3']['share_of_gain_lost']:.0f}% of D's gain at `h = 0.3`: the whole gain. The repair-set signal alone (signal 1) is *below* the best baseline ({f3(atr['D_only1']['auc_minus_best_baseline'])} AUC).
- Removing the repair-set signal makes D *better*: signal 3 alone reaches AUC {f3(P3['auc_0_to_6']['D_only3'])} against D_full's {f3(P3['auc_0_to_6']['D_full'])}. Signal 1 spends queries on connectivity guesses when the object or agent location is what is missing.
- So D_full's win over the baselines is carried entirely by one signal, the one that says which empty slots *must* hold facts (every object and agent has a location, every switch has a state, every location has a link).

## What that mechanism is (post hoc, labelled)

The preregistered baselines do not know that a `GATE` slot can never be identified as missing (an absent gate is indistinguishable from none), and a large share of empty-looking slots are gates. So a **graph-free schema rule**, query only empty-looking slots outside the `GATE` family, was run after the fact as a control. It needs no graph, no controller and no confidence for its random variant.

{chr(10).join(ex)}

- The schema-only control beats the preregistered best baseline (confidence) by {f3(xs['auc_diff']['S_schema_conf-B_confidence']['median'])} AUC at `h = 0.3`, far more than D_full does, and **D_full loses to it** ({f3(xs['auc_diff']['D_full-S_schema_conf']['median'])}) at every level.
- What graph structure adds beyond the schema rule is signal 3's increment: {f3(xs['auc_diff']['D_only3-S_schema_conf']['median'])} AUC at `h = 0.3` (interval {f3(xs['auc_diff']['D_only3-S_schema_conf']['ci95'][0])} to {f3(xs['auc_diff']['D_only3-S_schema_conf']['ci95'][1])}), not distinguishable from zero at `h = 0.15`, growing to {f3(XL['0.5']['auc_diff']['D_only3-S_schema_conf']['median'])} at `h = 0.5`. It is small next to the oracle headroom and it comes with a higher wrong-ACT rate: querying the most probable missing slot reveals enough to ACT early, sometimes wrongly (`D_only3` harm {pp(xs['harm']['D_only3'])}% against {pp(xs['harm']['S_schema_conf'])}% for the schema rule at `h = 0.3`).
- The ablation `D_only3` and the controls were not preregistered as contenders; they are reported to name the mechanism and do not change the verdict.

## Reading

1. The preregistered question, does a graph-guided policy beat the baselines on the recovery-cost frontier, is answered yes, and by the fixed rule X6-A continues.
2. The honest mechanism is **slot-type closure**: knowing which slot families must be populated. That is schema knowledge; a flat rule with no graph already captures about {100 * xs['auc_diff']['S_schema_conf-B_confidence']['median'] / (xs['auc_diff']['S_schema_conf-B_confidence']['median'] + xs['auc_diff']['D_only3-S_schema_conf']['median']):.0f}% of signal 3's gain over confidence acquisition at `h = 0.3`. The graph's own contribution (incoming links, bridge patterns) is small and unproven at low hiding.
3. The controller's goal-directed diagnostic (`repair_set`) is a poor acquisition signal in this environment: a repair that would make the goal reachable is not the fact that is missing.
4. Open, and not attempted here: acquisition where hiding can create conflict, where requestability differs by fact, and where the cost differs by slot. BANK-v1 has none of these, which is the case for doing this on BANK-v2 after V2-0 freezes its cue audit.

## Not claimed

No claim about learned or language-model acquisition, about text worlds, or about BANK-v2. The oracle selector is an upper bound only. Sensitivity to `h` is exploratory.
"""
(ROOT / "RESULTS.md").write_text(md, encoding="utf-8", newline="\n")
print("RESULTS.md written", len(md))
